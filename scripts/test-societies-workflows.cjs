'use strict';
const assert = require('node:assert/strict');
const { runtime, ok } = require('./test-societies.cjs');
const { membershipId } = require('../functions/societyManager/lib/common');
async function main() {
  const app = runtime();
  app.seed('societies', ['a', 'b', 'c'].map((_id, index) => ({ _id, name: _id, school: index === 0 ? '广州市第一中学' : index === 1 ? '广州大学' : '深圳大学', status: 'active', memberCount: 1, workCount: 0 })));
  app.seed('society_members', [['a', 'alice', 'owner'], ['b', 'bob', 'owner'], ['c', 'other', 'owner']].map(([societyId, userId, role]) => ({ _id: membershipId(societyId, userId), societyId, userId, userDocId: userId + '-doc', role, status: 'active', joinedAt: new Date() })));
  const future = hours => new Date(Date.now() + hours * 3600000).toISOString();
  const eventForm = { title: '秋分读诗会', description: '大家一起读诗', location: '图书馆403', startTime: future(48), endTime: future(50), registrationEnd: future(24), capacity: 1 };
  const save = (kind, form, extra = {}, caller = 'alice') => app.call({ action: 'saveContent', societyId: 'a', kind, form, requestId: 'create-' + kind, ...extra }, caller);
  assert.equal((await save('event', eventForm, {}, 'bob')).code, 'FORBIDDEN');
  app.state.moderationPassed = false;
  assert.equal((await save('event', eventForm)).success, false);
  assert.equal((app.tables.society_events || []).length, 0, 'failed moderation must not publish');
  app.state.moderationPassed = true;
  const news = await ok(save('news', { title: '动态', content: '以诗友芳邻' }));
  await ok(app.call({ action: 'changeContent', societyId: 'a', kind: 'news', id: news.id, revision: news.revision, operation: 'pin' }, 'alice'));
  assert.equal(app.tables.society_news[0].pinned, true);
  assert.equal((await app.call({ action: 'changeContent', societyId: 'a', kind: 'news', id: news.id, revision: news.revision, operation: 'delete' }, 'alice')).code, 'STALE_REVIEW');
  const event = await ok(save('event', eventForm));
  await ok(save('event', eventForm));
  assert.equal(app.tables.society_events.length, 1);
  assert.equal(app.tables.societies[0].eventCount, 1, 'idempotent creation counts once');
  const race = await Promise.all(['bob', 'other'].map(user => app.call({ action: 'registration', id: event.id, registered: true }, user)));
  assert.equal(race.filter(row => row.success).length, 1, 'last seat cannot be oversubscribed');
  const winner = race[0].success ? 'bob' : 'other';
  await ok(app.call({ action: 'registration', id: event.id, registered: true }, winner));
  assert.equal(app.tables.society_events[0].registrationCount, 1);
  assert.equal((await app.call({ action: 'registrations', id: event.id }, 'bob')).code, 'FORBIDDEN');
  const roster = await ok(app.call({ action: 'registrations', id: event.id }, 'alice'));
  assert.equal(roster.records.length, 1);
  assert.equal(roster.records[0].password, undefined);
  assert.equal((await save('event', { ...eventForm, capacity: 0 }, { id: event.id, revision: 0 })).code, 'STALE_REVIEW');
  await ok(app.call({ action: 'registration', id: event.id, registered: false }, winner));
  assert.equal(app.tables.society_events[0].registrationCount, 0);
  const onlyMembers = await ok(save('event', { ...eventForm, audience: 'members' }, { id: event.id, revision: 1 }));
  assert.equal((await app.call({ action: 'registration', id: event.id, registered: true }, 'bob')).code, 'FORBIDDEN');
  await ok(app.call({ action: 'registration', id: event.id, registered: true }, 'alice'));
  const call = await ok(save('call', { title: '联合征稿', description: '秋分与城市', deadline: future(24), invitedSocietyIds: ['b'] }));
  assert.equal((await app.call({ action: 'submissions', id: call.id, societyId: 'b' }, 'bob')).code, 'FORBIDDEN');
  assert.equal((await app.call({ action: 'acceptHost', id: call.id, societyId: 'c' }, 'other')).code, 'NOT_FOUND');
  await ok(app.call({ action: 'acceptHost', id: call.id, societyId: 'b' }, 'bob'));
  await ok(app.call({ action: 'submissions', id: call.id, societyId: 'b' }, 'bob'));
  app.seed('posts', [
    { _id: 'p1', _openid: 'bob', isPoem: true, isOriginal: true, title: '风', content: '风经过了诗页', auditStatus: 'approved', createTime: new Date() },
    { _id: 'p2', _openid: 'bob', isPoem: true, title: '雨', content: '雨落在城里', auditStatus: 'pending' },
    { _id: 'p3', _openid: 'bob', isPoem: true, title: '树', content: '树下', isHidden: true },
    { _id: 'p4', _openid: 'bob', isPoem: true, isOriginal: false, title: '云', content: '云在天上', auditStatus: 'approved' }
  ]);
  const submit = (postId = 'p1') => app.call({ action: 'submitWork', id: call.id, postId }, 'bob');
  assert.equal((await submit('p2')).success, false);
  assert.equal((await submit('p3')).success, false);
  assert.equal((await submit('p4')).success, false, 'non-original poems cannot be submitted');
  assert.equal((await app.call({ action: 'submitWork', id: call.id, postId: 'p1' }, 'other')).success, false);
  const [submission] = await Promise.all([ok(submit()), ok(submit())]);
  assert.equal(app.tables.society_submissions.length, 1);
  assert.equal(app.tables.society_calls[0].submissionCount, 1);
  const review = (decision, revision, caller = 'alice', societyId = 'a') => app.call({ action: 'reviewWork', id: submission.id, societyId, revision, decision }, caller);
  assert.equal((await review('approved', 1, 'other', 'c')).code, 'FORBIDDEN');
  await ok(review('deferred', 1));
  assert.deepEqual((await ok(app.call({ action: 'submissions', id: call.id, societyId: 'a', status: 'deferred' }, 'alice'))).records.map(row => row._id), [submission.id], 'previously deferred submissions remain available for later review');
  assert.equal((await review('approved', 1)).code, 'STALE_REVIEW');
  await ok(review('rejected', 2));
  await ok(submit());
  assert.equal(app.tables.society_submissions[0].revision, 4);
  app.tables.posts[0].content = '修改后的原诗';
  assert.equal((await review('approved', 4)).code, 'POST_CHANGED');
  await ok(review('rejected', 4));
  await ok(submit());
  const revision = app.tables.society_submissions[0].revision;
  app.state.failWrite = 'society_publications';
  assert.equal((await review('approved', revision)).success, false);
  assert.equal(app.tables.society_submissions[0].status, 'pending', 'review rolls back on publication failure');
  app.state.failWrite = '';
  await Promise.all([ok(review('approved', revision)), ok(review('approved', revision))]);
  assert.equal(app.tables.society_publications.length, 1);
  const callDetail = await ok(app.call({ action: 'opportunity', kind: 'call', id: call.id }));
  assert.deepEqual(callDetail.works.map(row => row._id), ['p1'], 'approved submissions appear on the call page');
  assert.equal(app.tables.societies[0].workCount, 1, 'concurrent approval publishes once');
  assert.equal(app.tables.posts.length, 4, 'publication never duplicates original posts');
  assert.equal((await app.call({ action: 'withdrawWork', id: submission.id, revision: revision + 1 }, 'bob')).success, false);
  const mine = await ok(app.call({ action: 'myParticipation', kind: 'call' }, 'bob'));
  assert.equal(mine.records[0].status, 'approved');
  assert.equal((await ok(app.call({ action: 'myParticipation' }, 'other'))).records.length, 0);
  const works = await ok(app.call({ action: 'myWorks', originalOnly: true }, 'bob'));
  assert.deepEqual(works.works.map(row => row._id), ['p1']);
  const associated = await ok(app.call({ action: 'myWorks' }, 'bob'));
  assert.deepEqual(associated.works.map(row => row._id).sort(), ['p1', 'p4'], 'association still accepts non-original poems');
  assert.equal((await app.call({ action: 'publishWork', societyId: 'a', postId: 'p1' }, 'bob')).code, 'FORBIDDEN');
  await Promise.all([1, 2].map(() => ok(app.call({ action: 'publishWork', societyId: 'b', postId: 'p1' }, 'bob'))));
  assert.equal(app.tables.societies[1].workCount, 1);
  const stats = (await ok(app.call({ action: 'statistics', societyId: 'a' }, 'alice'))).statistics;
  assert.equal(stats.registrations, 1);
  assert.equal(stats.submissions, 1);
  assert.equal(stats.weekWorks, 1);
  const page = await ok(app.call({ action: 'manageContent', societyId: 'b', kind: 'call' }, 'bob'));
  assert.equal(page.records[0]._id, call.id);
  const currentCalls = await ok(app.call({ action: 'callList', filter: 'current' }));
  assert.equal(currentCalls.calls.length, 1);
  assert.equal(currentCalls.calls[0].societyName, 'a');
  assert.equal(currentCalls.calls[0].statusLabel, '征稿中');
  assert.equal(currentCalls.calls[0].audience, 'all');
  assert.equal((await ok(app.call({ action: 'callList', filter: 'past' }))).calls.length, 0);
  const homeCalls = await ok(app.call({ action: 'home' }));
  assert.equal(homeCalls.calls.length, 1);
  assert.equal(homeCalls.pastCalls.length, 0);
  assert.equal(homeCalls.currentCallTotal, 1);
  app.tables.society_calls[0].deadline = new Date(Date.now() - 3600000);
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current' }))).calls.length, 0);
  assert.equal((await ok(app.call({ action: 'callList', filter: 'past' }))).calls.length, 1);
  const eventDetail = await ok(app.call({ action: 'opportunity', kind: 'event', id: event.id }));
  assert.equal(eventDetail.hosts.length, 1);
  assert.equal(eventDetail.hosts[0]._id, 'a');
  app.tables.society_events[0].registrationEnd = new Date(0);
  await ok(app.call({ action: 'registration', id: event.id, registered: false }, 'alice'));
  assert.equal((await app.call({ action: 'registration', id: event.id, registered: true }, 'alice')).code, 'CLOSED');
  await ok(app.call({ action: 'changeContent', societyId: 'a', kind: 'event', id: event.id, revision: onlyMembers.revision, operation: 'delete' }, 'alice'));
  assert.equal((await app.call({ action: 'opportunity', kind: 'event', id: event.id })).code, 'NOT_FOUND');
  await ok(save('call', { title: '内部征稿', description: '仅限本社成员投稿', deadline: future(24), audience: 'members' }, { requestId: 'members-call' }));
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current' }))).calls.length, 1);
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current', availableOnly: true }))).calls.length, 0, 'guests only see public calls when filtering');
  const memberCalls = await ok(app.call({ action: 'callList', filter: 'current', availableOnly: true }, 'alice'));
  assert.equal(memberCalls.calls.length, 1, 'host members see their members-only call');
  assert.equal(memberCalls.calls[0].statusLabel, '征稿中');
  assert.equal(memberCalls.calls[0].audience, 'members', 'the call list carries its saved scope');
  assert.equal((await ok(app.call({ action: 'opportunity', kind: 'call', id: memberCalls.calls[0]._id }))).item.audience, 'members', 'the call detail carries its saved scope');
  assert.equal((await ok(app.call({ action: 'editContent', societyId: 'a', kind: 'call', id: memberCalls.calls[0]._id }, 'alice'))).item.audience, 'members', 'editing keeps the saved scope');
  const schoolCall = await ok(save('call', { title: '本校征稿', description: '仅限本校学生投稿', deadline: future(48), audience: 'school' }, { requestId: 'school-call' }));
  assert.equal((await app.call({ action: 'callList', filter: 'current' })).calls.length, 2);
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current', availableOnly: true }))).calls.length, 0, 'guests cannot see school-only calls');
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current', availableOnly: true }, 'bob'))).calls.length, 0, 'users from another school cannot see school-only calls');
  app.user('bob').school = '广州';
  assert.equal((await ok(app.call({ action: 'callList', filter: 'current', availableOnly: true }, 'bob'))).calls.length, 1, 'school matching is fuzzy');
  assert.equal((await app.call({ action: 'submitWork', id: schoolCall.id, postId: 'p1' }, 'bob')).success, true);
  app.user('bob').school = '深圳';
  assert.equal((await app.call({ action: 'submitWork', id: schoolCall.id, postId: 'p1' }, 'bob')).code, 'FORBIDDEN', 'school scope is enforced on submission');
  console.log('societies workflows: PASS — moderation, permissions, invitations, capacity races, deadlines, idempotency, review versions, rollback, privacy, publication, call scope and statistics');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
